        let svc = test_auth_service();
        let hash = svc.hash_password("Correct-Horse-9!").unwrap();
        assert!(hash.starts_with("$argon2id$"), "{hash}");
        assert!(svc.check_password(&hash, "Correct-Horse-9!"));
